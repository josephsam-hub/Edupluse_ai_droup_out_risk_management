import React, { useState, useEffect } from 'react';
import {
  Users, AlertTriangle, CheckCircle, TrendingUp, Activity,
  BookOpen, UserCheck, RefreshCw
} from 'lucide-react';
import {
  PieChart, Pie, Cell, BarChart, Bar, XAxis, YAxis,
  CartesianGrid, Tooltip, Legend, ResponsiveContainer
} from 'recharts';
import { dashboardAPI } from '../services/api';
import { StatCard, SectionHeader, Spinner, ErrorBox } from '../components/UI';

const COLORS = { Low: '#10b981', Medium: '#f59e0b', High: '#ef4444' };

export default function Dashboard() {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  const fetchStats = async () => {
    setLoading(true);
    setError('');
    try {
      const res = await dashboardAPI.getStats();
      setData(res.data);
    } catch (e) {
      setError('Failed to load dashboard data. Make sure the backend is running.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => { fetchStats(); }, []);

  if (loading) return (
    <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', height: 300, gap: 12 }}>
      <Spinner size={28} /><span style={{ color: '#64748b', fontWeight: 600 }}>Loading dashboard analytics...</span>
    </div>
  );

  if (error) return <ErrorBox message={error} />;
  if (!data) return null;

  const { kpis, charts } = data;

  return (
    <div>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: '1.5rem' }}>
        <SectionHeader
          title="📊 Analytics Dashboard"
          subtitle="Real-time student risk overview powered by Machine Learning predictions"
        />
        <button className="btn-secondary" onClick={fetchStats} style={{ marginTop: 0 }}>
          <RefreshCw size={14} /> Refresh
        </button>
      </div>

      {/* Demo Banner */}
      <div style={{
        background: 'linear-gradient(135deg, #eff6ff 0%, #f0fdf4 100%)',
        border: '1px solid #bfdbfe', borderRadius: 10,
        padding: '0.75rem 1.25rem', marginBottom: '1.5rem',
        display: 'flex', alignItems: 'center', gap: 10
      }}>
        <span style={{ fontSize: '1.1rem' }}>🎓</span>
        <div>
          <span style={{ fontWeight: 700, color: '#1d4ed8', fontSize: '0.875rem' }}>Demo Dataset Active</span>
          <span style={{ color: '#64748b', fontSize: '0.8125rem', marginLeft: 8 }}>
            Showing {kpis.total_students} synthetic educational records — all predictions generated by Random Forest ML model
          </span>
        </div>
      </div>

      {/* KPI Cards */}
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(180px, 1fr))', gap: '1rem', marginBottom: '1.75rem' }}>
        <StatCard icon={<Users />} label="Total Students" value={kpis.total_students} color="#2563eb" />
        <StatCard icon={<CheckCircle />} label="Low Risk" value={kpis.low_risk_count} color="#10b981" sub="Progressing well" />
        <StatCard icon={<AlertTriangle />} label="Medium Risk" value={kpis.medium_risk_count} color="#f59e0b" sub="Monitor closely" />
        <StatCard icon={<AlertTriangle />} label="High Risk" value={kpis.high_risk_count} color="#ef4444" sub="Immediate action needed" />
        <StatCard icon={<Activity />} label="Avg Attendance" value={`${kpis.avg_attendance}%`} color="#8b5cf6" />
        <StatCard icon={<BookOpen />} label="Avg GPA" value={kpis.avg_gpa} color="#0891b2" sub="Out of 10.0" />
        <StatCard icon={<UserCheck />} label="Interventions" value={kpis.interventions_needed} color="#dc2626" sub="Pending actions" />
      </div>

      {/* Charts Row 1 */}
      <div style={{ display: 'grid', gridTemplateColumns: '340px 1fr', gap: '1.25rem', marginBottom: '1.25rem' }}>
        {/* Pie Chart */}
        <div className="card">
          <div style={{ fontWeight: 700, color: '#0f172a', marginBottom: '1rem', fontSize: '0.9375rem' }}>
            Risk Distribution
          </div>
          <ResponsiveContainer width="100%" height={220}>
            <PieChart>
              <Pie data={charts.risk_distribution} cx="50%" cy="50%" outerRadius={80}
                dataKey="value" nameKey="name" label={({ name, percent }) => `${name}: ${(percent * 100).toFixed(0)}%`}
                labelLine={false}
              >
                {charts.risk_distribution.map((entry, i) => (
                  <Cell key={i} fill={entry.color} />
                ))}
              </Pie>
              <Tooltip formatter={(v) => [`${v} students`, '']} />
            </PieChart>
          </ResponsiveContainer>
        </div>

        {/* Department Risk Bar */}
        <div className="card">
          <div style={{ fontWeight: 700, color: '#0f172a', marginBottom: '1rem', fontSize: '0.9375rem' }}>
            Department-wise Risk Breakdown
          </div>
          <ResponsiveContainer width="100%" height={220}>
            <BarChart data={charts.department_risk}>
              <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
              <XAxis dataKey="department" tick={{ fontSize: 11 }}
                tickFormatter={v => v.replace(' Eng', '').substring(0, 12)} />
              <YAxis tick={{ fontSize: 11 }} />
              <Tooltip />
              <Legend wrapperStyle={{ fontSize: 11 }} />
              <Bar dataKey="Low" fill="#10b981" stackId="a" />
              <Bar dataKey="Medium" fill="#f59e0b" stackId="a" />
              <Bar dataKey="High" fill="#ef4444" stackId="a" radius={[4, 4, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </div>
      </div>

      {/* Charts Row 2 */}
      <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '1.25rem', marginBottom: '1.25rem' }}>
        {/* GPA vs Risk */}
        <div className="card">
          <div style={{ fontWeight: 700, color: '#0f172a', marginBottom: '1rem', fontSize: '0.9375rem' }}>
            GPA Range vs Dropout Risk
          </div>
          <ResponsiveContainer width="100%" height={200}>
            <BarChart data={charts.gpa_vs_risk}>
              <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
              <XAxis dataKey="bucket" tick={{ fontSize: 10 }} />
              <YAxis tick={{ fontSize: 11 }} />
              <Tooltip />
              <Legend wrapperStyle={{ fontSize: 11 }} />
              <Bar dataKey="Low" fill="#10b981" stackId="a" />
              <Bar dataKey="Medium" fill="#f59e0b" stackId="a" />
              <Bar dataKey="High" fill="#ef4444" stackId="a" radius={[3, 3, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </div>

        {/* Attendance vs Risk */}
        <div className="card">
          <div style={{ fontWeight: 700, color: '#0f172a', marginBottom: '1rem', fontSize: '0.9375rem' }}>
            Attendance vs Dropout Risk
          </div>
          <ResponsiveContainer width="100%" height={200}>
            <BarChart data={charts.attendance_vs_risk}>
              <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
              <XAxis dataKey="bucket" tick={{ fontSize: 10 }} />
              <YAxis tick={{ fontSize: 11 }} />
              <Tooltip />
              <Legend wrapperStyle={{ fontSize: 11 }} />
              <Bar dataKey="Low" fill="#10b981" stackId="a" />
              <Bar dataKey="Medium" fill="#f59e0b" stackId="a" />
              <Bar dataKey="High" fill="#ef4444" stackId="a" radius={[3, 3, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </div>
      </div>

      {/* Semester Risk */}
      {charts.semester_risk?.length > 0 && (
        <div className="card">
          <div style={{ fontWeight: 700, color: '#0f172a', marginBottom: '1rem', fontSize: '0.9375rem' }}>
            Semester-wise Risk Distribution
          </div>
          <ResponsiveContainer width="100%" height={200}>
            <BarChart data={charts.semester_risk}>
              <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
              <XAxis dataKey="semester" tick={{ fontSize: 11 }} />
              <YAxis tick={{ fontSize: 11 }} />
              <Tooltip />
              <Legend wrapperStyle={{ fontSize: 11 }} />
              <Bar dataKey="Low" fill="#10b981" stackId="a" />
              <Bar dataKey="Medium" fill="#f59e0b" stackId="a" />
              <Bar dataKey="High" fill="#ef4444" stackId="a" radius={[3, 3, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        </div>
      )}
    </div>
  );
}
